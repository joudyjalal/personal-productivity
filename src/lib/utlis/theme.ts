export function applyTheme(themeKey: keyof typeof customThemes, mode: "light" | "dark") {
  const theme = customThemes[themeKey];
  if (!theme) return;

  const variables = theme[mode];
  Object.entries(variables).forEach(([key, value]) => {
    document.documentElement.style.setProperty(key, value);
  });


  localStorage.setItem("life_os_custom_theme", themeKey);
}